import {chromium,expect} from '@playwright/test';
const browser=await chromium.launch({headless:true,channel:'msedge'});
const page=await browser.newPage({viewport:{width:390,height:844}});
await page.goto('http://127.0.0.1:5192/');
await page.getByRole('button',{name:'Explore the local demo'}).click();
await page.getByRole('button',{name:'Skip onboarding'}).click();
await page.getByRole('button',{name:'Explore strength check'}).click();
await page.getByRole('button',{name:'Skip for now',exact:true}).click();
await expect(page.getByRole('button',{name:'Start optional strength check'})).toHaveCount(0);
await page.getByRole('button',{name:'Explore strength check'}).click();
await page.getByRole('button',{name:'Start optional strength check'}).click();
await expect(page.getByText('Warm up what you’ll train.',{exact:true})).toBeVisible();
await page.getByRole('button',{name:'Skip warm-up',exact:true}).click();
await expect(page.getByRole('spinbutton',{name:'Set 1 weight in kg',exact:true})).toHaveValue('0');
await page.getByRole('button',{name:'Manageable',exact:true}).click();
await page.getByRole('button',{name:'Complete set 1',exact:true}).click();
await page.getByRole('button',{name:'Finish',exact:true}).click();
await page.getByRole('button',{name:'Save workout',exact:true}).click();
await page.getByRole('navigation',{name:'Mobile navigation'}).getByRole('button',{name:'Today',exact:true}).click();
await expect(page.getByText(/Latest baseline/)).toBeVisible();
await page.getByText(/Latest baseline/).click();
await expect(page.getByText('Baseline effort: Manageable',{exact:true})).toBeVisible();
console.log('Optional skip, warm-up, zero seeded load, effort and saved baseline passed on mobile.');
await browser.close();
