import fs from 'node:fs';
// Editorial selection of familiar gym movements; not a measured popularity ranking.
const groups={
 squat:[1810,1811,1822,1874,1915,1916,1920,2073],
 lunge:[1918,1919],
 hinge:[1292,1305,1321,1329],
 bridge:[1232,1233],
 bench:[927,928,929,932,1052,1105,1107,1111],
 pushup:[960,963],
 row:[1640,1669,1670,1673],
 seatedRow:[1495,1698],
 pulldown:[1473,1494],
 curl:[707,708,709,732,734,736,819,858],
 press:[2450,2451,2529,2534,2715],
 lateralRaise:[2545,2550],
 frontRaise:[2542],
 pushdown:[2833,2834,2838],
 overheadExtension:[2792,2794,2842],
 skullcrusher:[2798,2912],
 legCurl:[1348],
 legExtension:[2074],
};
const catalog=JSON.parse(fs.readFileSync('src/data/gym-exercises.json','utf8'));
const profiles=Object.entries(groups).flatMap(([family,ids])=>ids.map(number=>{
 const exercise=catalog.find(e=>e.id.startsWith(`gym-${number}-`));
 if(!exercise)throw Error(`Missing catalog exercise ${number}`);
 return {id:exercise.id,name:exercise.name,family};
}));
if(profiles.length!==60||new Set(profiles.map(p=>p.id)).size!==60)throw Error('Expected 60 distinct exercises');
fs.writeFileSync('src/ai/priority-profiles.ts',`// Generated by scripts/generate-priority-ai.mjs. Editorial shortlist, not measured usage.\nimport type {PriorityFamily} from './priority-motion';\nexport const priorityProfiles=${JSON.stringify(profiles,null,2)} as const satisfies readonly {id:string;name:string;family:PriorityFamily}[];\n`);
console.log('Selected 60 exact catalog exercises.');
