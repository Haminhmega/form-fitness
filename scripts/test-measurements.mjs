import assert from 'node:assert/strict';
import {build} from 'esbuild';
const result=await build({stdin:{contents:"export * from './src/measurements.ts'; export {profileSchema} from './shared/account.ts';",resolveDir:process.cwd()},bundle:true,format:'esm',platform:'node',write:false});
const {createMeasurements,editMeasurement,changeMeasurementUnits,hasInvalidMeasurements,formatHeight,profileSchema}=await import('data:text/javascript;base64,'+Buffer.from(result.outputFiles[0].text).toString('base64'));
const original={heightCm:172.739,weightKg:63.823456,targetWeightKg:66.6789};
let state=createMeasurements(original,'kg');
for(let i=0;i<100;i++)state=changeMeasurementUnits(state,i%2?'kg':'lb');
assert.deepEqual(state.values,original,'Repeated toggles preserve exact saved measurements');
state=changeMeasurementUnits(state,'lb');
state=editMeasurement(state,'weight','150');
assert.ok(Math.abs(state.values.weightKg-68.0388555)<0.00001);
assert.equal(state.values.heightCm,original.heightCm,'Editing weight leaves the unrounded height intact');
state=editMeasurement(editMeasurement(state,'heightFeet','5'),'heightInches','8');
assert.ok(Math.abs(state.values.heightCm-172.72)<0.00001);
assert.equal(formatHeight(172.72,'lb'),'5 ft 8 in');
assert.equal(formatHeight(182.88,'lb'),'6 ft 0 in');
state=editMeasurement(state,'heightInches','12');
assert.equal(hasInvalidMeasurements(state),true,'Twelve inches is not silently accepted as another foot');
state=editMeasurement(state,'heightInches','-1');
assert.equal(hasInvalidMeasurements(state),true);
state=editMeasurement(editMeasurement(state,'heightFeet','5.5'),'heightInches','1');
assert.equal(hasInvalidMeasurements(state),true,'Feet must be whole numbers');
state=editMeasurement(editMeasurement(state,'heightFeet',''),'heightInches','');
state=editMeasurement(editMeasurement(state,'weight',''),'target','');
assert.deepEqual(changeMeasurementUnits(state,'kg').values,{heightCm:null,weightKg:null,targetWeightKg:null});
assert.deepEqual(changeMeasurementUnits(state,'kg').fields,{height:'',heightFeet:'',heightInches:'',weight:'',target:''},'Optional blanks never turn into zeroes');
const valid=values=>profileSchema.safeParse({name:'Tester',age:null,activity:'Lightly active',...values}).success;
for(const bounds of [{heightCm:50,weightKg:20,targetWeightKg:20},{heightCm:260,weightKg:500,targetWeightKg:500}])assert.equal(valid(changeMeasurementUnits(createMeasurements(bounds,'kg'),'lb').values),true,'Boundary values survive imperial display rounding');
assert.equal(valid({...original,weightKg:19.99}),false);
assert.equal(valid({...original,heightCm:260.01}),false);
assert.equal(valid({...original,targetWeightKg:500.01}),false);
console.log('Body measurements: conversions, optional fields, bounds and repeated toggles passed.');
