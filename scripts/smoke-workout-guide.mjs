import {chromium,expect} from '@playwright/test';
const browser=await chromium.launch({headless:true,channel:'msedge'});
try {
 const page=await browser.newPage({viewport:{width:390,height:844}});
 await page.goto('http://127.0.0.1:5192/');
 await page.getByRole('button',{name:'Explore the local demo'}).click();
 await page.getByRole('button',{name:'Skip onboarding'}).click();
 await page.getByRole('button',{name:'Explore strength check'}).click();
 await page.getByRole('button',{name:'Start optional strength check'}).click();
 await page.getByRole('button',{name:'Skip warm-up',exact:true}).click();
 const guide=page.locator('.workout-guide');
 await expect(guide.getByRole('heading',{name:'Step by step',exact:true})).toBeVisible();
 const squatSteps=await guide.locator('.train-guide-copy li p').allTextContents();
 await page.getByRole('spinbutton',{name:'Set 1 reps',exact:true}).fill('9');
 await guide.locator(':scope > summary').click();
 await expect(guide.getByRole('heading',{name:'Step by step',exact:true})).not.toBeVisible();
 await page.locator('.session-exercise').filter({hasText:'Forearm plank'}).click();
 await expect(guide.locator(':scope > summary')).toHaveText('How to do Forearm plank');
 await expect(guide.getByRole('heading',{name:'Step by step',exact:true})).toBeVisible();
 await guide.getByText('See this movement',{exact:true}).click();
 await expect(guide.locator('.exercise-demo')).toBeVisible();
 await page.locator('.session-exercise').filter({hasText:'Bodyweight squat'}).click();
 await expect(page.getByRole('spinbutton',{name:'Set 1 reps',exact:true})).toHaveValue('9');
 await expect(guide.locator('.train-guide-copy li p')).toHaveText(squatSteps);
 await guide.getByText('Target muscles, grip & movement path',{exact:true}).click();
 await expect(guide.getByRole('heading',{name:'What this movement emphasizes'})).toBeVisible();
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
 await page.screenshot({path:'../workout-guide-mobile.png',fullPage:true});
 await page.getByRole('navigation',{name:'Mobile navigation'}).getByRole('button',{name:'Train',exact:true}).click();
 await page.getByRole('tab',{name:'Exercise library'}).click();
 await page.getByRole('checkbox',{name:'60 common exercises · focused beta checks'}).check();
 await expect(page.locator('.train-exercise-row')).toHaveCount(60);
 await page.getByRole('button',{name:'View Lying Leg Curls details',exact:true}).click();
 await page.getByRole('button',{name:'Check a video of this exercise'}).click();
 await expect(page.getByRole('heading',{name:'Lying Leg Curls',exact:true}).first()).toBeVisible();
 await expect(page.getByText(/Real-world accuracy has not been validated/)).toBeVisible();
 await expect(page.getByText(/Begin with knees extended/).first()).toBeVisible();
 await page.setViewportSize({width:1440,height:1000});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Desktop overflow');
 console.log('Workout instructions, exercise switching, preserved logs, muscle details, 60-exercise filter, direct analysis entry and validation disclosure passed.');
} finally {await browser.close();}
