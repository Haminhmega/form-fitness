import fs from 'node:fs';

const catalog=JSON.parse(fs.readFileSync(new URL('../src/data/gym-exercises.json',import.meta.url),'utf8'));
const muscles=new Set(['Quadriceps','Hamstrings','Glutes','Lower Back','Chest','Biceps','Triceps','Lats','Middle Back','Shoulders']);
const excluded=/plank|crawl|hold|static|isometric|stretch|jump|clean|snatch|muscle up|throw|spell caster|sit-through/i;
const profileFor=(exercise)=>{
  const name=exercise.name.toLowerCase();
  if(/squat|lunge|leg press|leg extension/.test(name)||exercise.muscle==='Quadriceps')return 'knee';
  if(/deadlift|good morning|hip|glute|back extension|hyperextension|leg curl|glute ham/.test(name)||['Hamstrings','Glutes','Lower Back'].includes(exercise.muscle))return 'hip';
  if(/raise|fly|crossover/.test(name)||exercise.muscle==='Shoulders')return 'shoulder';
  return 'elbow';
};
const selected=catalog
  .filter(e=>e.category==='Strength'&&typeof e.rating==='number'&&e.rating>=8.5&&muscles.has(e.muscle)&&!excluded.test(e.name))
  .sort((a,b)=>b.rating-a.rating||a.name.localeCompare(b.name))
  .slice(0,95)
  .map(e=>({id:e.id,name:e.name,profile:profileFor(e),rating:e.rating}));
if(selected.length!==95)throw new Error(`Expected 95 eligible catalog exercises, found ${selected.length}`);
const out=`// Generated by scripts/generate-popular-ai.mjs from the CC0 Gym Exercise Dataset.\n`+
  `// Rating is used as a documented popularity proxy; these are beta motion checks, not validated form grades.\n`+
  `export type MotionProfile='knee'|'hip'|'elbow'|'shoulder';\n`+
  `export const popularExerciseProfiles=${JSON.stringify(selected,null,2)} as const;\n`;
fs.writeFileSync(new URL('../src/ai/popular-profiles.ts',import.meta.url),out);
console.log(`Generated ${selected.length} beta exercise profiles.`);
